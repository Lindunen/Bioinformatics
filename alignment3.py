score_linear = 0
for a, b in zip(align1_linear, align2_linear):
    if a == '-' or b == '-':
        score_linear += -4
    elif a == b:
        score_linear += 1
    else:
        score_linear += -1
print(f"SCORE: {score_linear}")

M, X, Y, score_affine = needleman_wunsch_affine(seq1, seq2, match=1, mismatch=-1, gap_open=-10, gap_extend=-1)

